from typing import Protocol
from fastapi import WebSocket

from src.domain.notification import Notification

class Notifier(Protocol):
    async def SendAboutNewEvents(self, user_id: int, notification: Notification): ...
    async def SendAboutNewDescussionMessages(self, user_id: int, notification: Notification ): ...
    async def SendAboutNewFeedBack(self, user_id: int, notification: Notification): ...

    async def Connect(self, websocket: WebSocket, user_id: int): ...
    async def Disconnect(self, user_id: int): ...