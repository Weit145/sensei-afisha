from typing import Protocol
from fastapi import WebSocket

from src.domain.notification import Notification

class Notifier(Protocol):
    async def SendAboutNewEvents(self, user_ip: str,  notification: Notification)->None: ...
    async def SendAboutNewDescussionMessages(self, user_ip: str, notification: Notification )->None: ...
    async def SendAboutNewFeedBack(self, user_ip: str, notification: Notification)->None: ...

    async def Connect(self, websocket: WebSocket, user_id: int)->bool: ...
    async def Disconnect(self, user_id: int)->bool: ...

    async def CheckNotificationConnection()->bool: ...

    async def Subscribe()->None:...
    async def Unsubscribe()->None: ...
    async def SwitchRoom()->None: ...